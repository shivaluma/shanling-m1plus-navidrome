#!/usr/bin/env python3
"""Generate backend/nfc_table.go: canonical Latin/Greek/Cyrillic compositions.

The device font renderer has no shaping, so decomposed (NFD) metadata such as
macOS-derived Vietnamese file names would draw overlapping accents. The backend
composes these pairs; the Go standard library has no normalization package.
"""
from pathlib import Path
import unicodedata

ROOT = Path(__file__).resolve().parents[1]
RANGES = ((0x00C0, 0x024F), (0x0370, 0x03FF), (0x0400, 0x04FF), (0x1E00, 0x1EFF), (0x1F00, 0x1FFF))


def pairs():
    for start, end in RANGES:
        for code in range(start, end + 1):
            parts = unicodedata.decomposition(chr(code)).split()
            if len(parts) != 2 or parts[0].startswith('<'):
                continue
            base, mark = (int(p, 16) for p in parts)
            # Excludes composition exclusions and singleton decompositions.
            if unicodedata.combining(chr(mark)) and unicodedata.normalize('NFC', chr(base) + chr(mark)) == chr(code):
                yield base, mark, code


def main():
    rows = sorted(pairs())
    lines = ['// Code generated by scripts/gen_nfc_table.py from Python ' + unicodedata.unidata_version +
             ' Unicode data; DO NOT EDIT.', '', 'package main', '',
             'var nfcPairs = map[[2]rune]rune{']
    lines += [f'\t{{0x{b:04X}, 0x{m:04X}}}: 0x{c:04X},' for b, m, c in rows]
    lines += ['}', '']
    (ROOT / 'backend/nfc_table.go').write_text('\n'.join(lines))
    print(f'{len(rows)} composition pairs')


if __name__ == '__main__':
    main()
